<?php

$vendorDir = __DIR__.'/vendor';
$composerDir = $vendorDir.'/composer';
$installedJsonPath = $composerDir.'/installed.json';

if (! file_exists($installedJsonPath)) {
    exit("installed.json not found!\n");
}

$installed = json_decode(file_get_contents($installedJsonPath), true);
$rootComposer = json_decode(file_get_contents(__DIR__.'/composer.json'), true);

$packages = $installed['packages'] ?? $installed;

$psr4 = [];
$psr0 = [];
$classmap = [];
$files = [];

// Root package autoload
if (isset($rootComposer['autoload']['psr-4'])) {
    foreach ($rootComposer['autoload']['psr-4'] as $prefix => $paths) {
        $paths = (array) $paths;
        foreach ($paths as $path) {
            $psr4[$prefix][] = '$baseDir . \'/'.trim($path, '/').'\'';
        }
    }
}
if (isset($rootComposer['autoload']['files'])) {
    foreach ($rootComposer['autoload']['files'] as $file) {
        $files[] = '$baseDir . \'/'.trim($file, '/').'\'';
    }
}

// Packages autoload
foreach ($packages as $pkg) {
    $installPath = $pkg['install-path'] ?? ('../'.$pkg['name']);
    $pkgDir = '$vendorDir . \'/'.trim(str_replace('../', '', $installPath), '/').'\'';

    if (isset($pkg['autoload']['psr-4'])) {
        foreach ($pkg['autoload']['psr-4'] as $prefix => $paths) {
            $paths = (array) $paths;
            foreach ($paths as $path) {
                $subPath = $path ? ('/'.trim($path, '/')) : '';
                $psr4[$prefix][] = '$vendorDir . \'/'.trim(str_replace('../', '', $installPath), '/').$subPath.'\'';
            }
        }
    }

    if (isset($pkg['autoload']['psr-0'])) {
        foreach ($pkg['autoload']['psr-0'] as $prefix => $paths) {
            $paths = (array) $paths;
            foreach ($paths as $path) {
                $subPath = $path ? ('/'.trim($path, '/')) : '';
                $psr0[$prefix][] = '$vendorDir . \'/'.trim(str_replace('../', '', $installPath), '/').$subPath.'\'';
            }
        }
    }

    if (isset($pkg['autoload']['classmap'])) {
        foreach ($pkg['autoload']['classmap'] as $path) {
            $subPath = $path ? ('/'.trim($path, '/')) : '';
            $classmap[] = '$vendorDir . \'/'.trim(str_replace('../', '', $installPath), '/').$subPath.'\'';
        }
    }

    if (isset($pkg['autoload']['files'])) {
        foreach ($pkg['autoload']['files'] as $file) {
            $files[] = '$vendorDir . \'/'.trim(str_replace('../', '', $installPath), '/').'/'.trim($file, '/').'\'';
        }
    }
}

// Copy ClassLoader.php from global composer or write clean standard Composer ClassLoader
$classLoaderSource = 'C:/Users/Administrator/AppData/Roaming/Composer/vendor/composer/ClassLoader.php';
if (file_exists($classLoaderSource)) {
    copy($classLoaderSource, $composerDir.'/ClassLoader.php');
}

// Build autoload_psr4.php
$psr4Content = "<?php\n\n// autoload_psr4.php @generated\n\n\$vendorDir = dirname(__DIR__);\n\$baseDir = dirname(\$vendorDir);\n\nreturn array(\n";
foreach ($psr4 as $prefix => $dirs) {
    $psr4Content .= '    '.var_export($prefix, true).' => array('.implode(', ', $dirs)."),\n";
}
$psr4Content .= ");\n";
file_put_contents($composerDir.'/autoload_psr4.php', $psr4Content);

// Build autoload_namespaces.php
$psr0Content = "<?php\n\n// autoload_namespaces.php @generated\n\n\$vendorDir = dirname(__DIR__);\n\$baseDir = dirname(\$vendorDir);\n\nreturn array(\n";
foreach ($psr0 as $prefix => $dirs) {
    $psr0Content .= '    '.var_export($prefix, true).' => array('.implode(', ', $dirs)."),\n";
}
$psr0Content .= ");\n";
file_put_contents($composerDir.'/autoload_namespaces.php', $psr0Content);

// Build autoload_classmap.php
$classmapContent = "<?php\n\n// autoload_classmap.php @generated\n\n\$vendorDir = dirname(__DIR__);\n\$baseDir = dirname(\$vendorDir);\n\nreturn array(\n";
$classmapContent .= ");\n";
file_put_contents($composerDir.'/autoload_classmap.php', $classmapContent);

// Build autoload_files.php
$filesContent = "<?php\n\n// autoload_files.php @generated\n\n\$vendorDir = dirname(__DIR__);\n\$baseDir = dirname(\$vendorDir);\n\nreturn array(\n";
foreach ($files as $idx => $f) {
    $filesContent .= '    md5('.$f.') => '.$f.",\n";
}
$filesContent .= ");\n";
file_put_contents($composerDir.'/autoload_files.php', $filesContent);

// Build autoload_real.php
$randId = md5(microtime());
$realContent = <<<PHP
<?php

// autoload_real.php @generated by Composer

class ComposerAutoloaderInit{$randId}
{
    private static \$loader;

    public static function loadClassLoader(\$class)
    {
        if ('Composer\\Autoload\\ClassLoader' === \$class) {
            require __DIR__ . '/ClassLoader.php';
        }
    }

    /**
     * @return \\Composer\\Autoload\\ClassLoader
     */
    public static function getLoader()
    {
        if (null !== self::\$loader) {
            return self::\$loader;
        }

        require __DIR__ . '/platform_check.php';

        spl_autoload_register(array('ComposerAutoloaderInit{$randId}', 'loadClassLoader'), true, true);
        self::\$loader = \$loader = new \\Composer\\Autoload\\ClassLoader(\\dirname(__DIR__));
        spl_autoload_unregister(array('ComposerAutoloaderInit{$randId}', 'loadClassLoader'));

        \$map = require __DIR__ . '/autoload_namespaces.php';
        foreach (\$map as \$namespace => \$path) {
            \$loader->set(\$namespace, \$path);
        }

        \$map = require __DIR__ . '/autoload_psr4.php';
        foreach (\$map as \$namespace => \$path) {
            \$loader->setPsr4(\$namespace, \$path);
        }

        \$classMap = require __DIR__ . '/autoload_classmap.php';
        if (\$classMap) {
            \$loader->addClassMap(\$classMap);
        }

        \$loader->register(true);

        \$filesToLoad = require __DIR__ . '/autoload_files.php';
        \$checkFunctions = function (\$fileIdentifier, \$file) {
            if (empty(\$GLOBALS['__composer_autoload_files'][\$fileIdentifier])) {
                \$GLOBALS['__composer_autoload_files'][\$fileIdentifier] = true;
                require \$file;
            }
        };
        foreach (\$filesToLoad as \$fileIdentifier => \$file) {
            (\$checkFunctions)(\$fileIdentifier, \$file);
        }

        return \$loader;
    }
}
PHP;
file_put_contents($composerDir.'/autoload_real.php', $realContent);

// Build platform_check.php
$platformContent = "<?php\n// platform_check.php\n";
file_put_contents($composerDir.'/platform_check.php', $platformContent);

// Build vendor/autoload.php
$autoloadContent = <<<PHP
<?php

// autoload.php @generated by Composer

require_once __DIR__ . '/composer/autoload_real.php';

return ComposerAutoloaderInit{$randId}::getLoader();
PHP;
file_put_contents($vendorDir.'/autoload.php', $autoloadContent);

echo "Autoload successfully generated!\n";
